def _continuity(blocks):
    """上下镜衔接：相邻两镜须有共用关键物件/人物字，否则标可能虚接。WARN 机器先揪。"""
    res = []
    for i in range(1, len(blocks)):
        prev_k = _keychars(blocks[i-1])
        cur_k = _keychars(blocks[i])
        if not cur_k:
            continue
        if not (prev_k & cur_k):
            res.append(("上下镜衔接", "镜%d 与 镜%d 可能虚接：相邻两镜无共用关键物件/人物（机器先揪，需人工核对方位/动作/转场是否真接上）" % (i, i+1)))
    return res


def scan_storyboard_shots(text: str, m1_text: str = None) -> list:
    """分镜正文逐镜质检：每镜至少一句台词 + 台词书面腔 + 场景对不上 + 上下镜衔接。机器先揪，人工最终判。
    与离线工具 m2_gate / m2_connchk 口径一致。"""
    issues = []
    body = re.split(r'##\s*③?\s*附表', text)[0]   # 取到分镜正文（兼容「## 附表」与「## ③ 附表」）
    blocks = re.findall(r'\**镜\d+\b[^\n]*\n(.*?)(?=\n\s*\**镜\d+\b[^\n]*\n|\Z)', body, re.S)
    for si, blk in enumerate(blocks, 1):
        if not blk.strip():
            continue
        # 七项：镜块内只要存在一个「男/女开头+6分隔」的括号即合规（镜号行/章节括号不误伤）
        braces = re.findall(r'[（(]([^）)]*)[）)]', blk)
        if not any(re.match(r'^(男|女)·', b) and b.count('·') == 6 for b in braces):
            issues.append((0, "台词标注缺项", "镜%d 缺合规七项（性别·年纪·声线·语气·语速·情绪·氛围，首项男/女+6分隔）" % si, blk.strip()[:40]))
        # 每镜至少一句台词（任意引号：" " 「 」）
        if not re.search(r'["“\u300c]', blk):
            issues.append((0, "每镜缺台词", "镜%d 纯画面无台词" % si, blk.strip()[:40]))
        # 台词书面腔：先剔除角色括号七项，再查鸡汤词（避免「语气感慨」误伤）
        cleaned = re.sub(r'[（(][^）)]*[）)]', '', blk)
        for w in AI_FLAVOR_WORDS:
            if w in cleaned:
                issues.append((0, "台词书面腔", "镜%d 疑似书面腔：「%s」" % (si, w), blk.strip()[:40]))
    # 场景对不上（例如城里高楼配农村堂屋、回胡同却上电梯）——全文级
    for cat, msg in _scene_logic(body):
        issues.append((0, cat, msg, "分镜正文"))
    # 上下镜衔接（相邻镜须有共用关键物件/人物）——跨镜级
    for cat, msg in _continuity(blocks):
        issues.append((0, cat, msg, ""))
    # 前后对不上四查（C1/C2/C3）：与两道交付门同源，机器先揪、人工最终判
    for c, msg in consist_chk.line_issues(text, "m2", m1_text):
        issues.append((0, "前后对不上 " + c, msg, "全篇"))
    return issues



def scan_text(text: str, stage: str = "script", m1_text: str = None) -> list:
    """扫交付文档。stage='storyboard' 时额外扫分镜正文里的要求词、影视术语、小标题、时间轴条目。"""
    issues = []
    in_board = False
    in_req = False          # 「⑥ 分镜脚本将按什么要求制作」是要求节，不是正文，禁词不适用
    for idx, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line:
            continue
        if line.startswith("## "):
            in_req = line.startswith("## ⑥")
        if line.startswith("## ") and "附表" in line:
            break   # 附表是清单与对照，不是叙事正文；两道交付门都只扫附表之前
        if in_req:
            continue
        if line.startswith("## ③") and "分镜" in line:
            in_board = True
        elif line.startswith("## ") and ("附表" in line or "③b" in line or "④ 角色卡" in line
                                         or "⑤ " in line or "⑥ " in line or "⑦ " in line):
            in_board = False
        if any(h in line for h in WHITELIST_HINTS):
            continue
        cmp_line = line.replace("合同上", "合同 ").replace("一同上", "一同 ")
        for w in BANNED_STRUCT:
            if w in cmp_line:
                issues.append((idx, "结构禁词", w, line[:60]))
        for cat, pats in BANNED_PATTERNS.items():
            # 抽象时间词只管画面正文；对照表、人物设定、前提表里交代背景年份属正常，不算把时间写进画面
            if cat == "抽象时间词" and (line.startswith("|") or line.startswith("- ")):
                continue
            for p in pats:
                m = re.search(p, line)
                if m:
                    issues.append((idx, cat, m.group(0), line[:60]))
        for v in VAGUE_ACTIONS:
            pos = line.find(v)
            while pos != -1:
                lead = line[max(0, pos - 8):pos]
                tail = line[pos + len(v): pos + len(v) + 3]
                # 写明哪只手、或写明扶的是门框/门沿/把手，动作已落地，不算模糊
                specific = (re.search(r"(左手|右手|左臂|右臂|指|掌|一手|单手)", lead)
                            or re.match(r"(框|沿|把|边|板)", tail))
                if not specific:
                    issues.append((idx, "模糊动作", v, line[:60]))
                    break
                pos = line.find(v, pos + 1)
        if re.search(r"(?<!\d)(\d{4})年", line) or re.search(r"\d{1,2}月\d{1,2}日", line):
            issues.append((idx, "日期入画面", "出现具体年月日", line[:60]))
        if stage != "storyboard" and re.match(u"^段\\s*\\d", line):
            for w in BANNED_JARGON + BANNED_LABELS:
                if w in line:
                    issues.append((idx, "影视术语／要求句", w, line[:60]))
        if in_board and stage == "storyboard":
            if line.startswith('>'):
                continue  # 说明/注释行（如「生成方式…」）不查正文禁词，避免骨架注释误伤
            # 分镜一律一镜一段散文：禁止的是【】字段行、「取景：」小标题、时间轴条目、
            # 括号景别标签。取景/运镜/构图/光影四项按用户规范必须用中英对照专业术语，
            # 术语后置括注落进句子成分是正选，正文出现英文原词与中文释义都不判违规。
            if re.search(u"【[^】]*】", line):
                issues.append((idx, "技术标签行", u"分镜不许【】标签，九项信息写进句子", line[:60]))
            for w in BANNED_LABELS:
                if w in line:
                    issues.append((idx, "小标题标签", w, line[:60]))
            if TIMELINE_PAT.search(line):
                issues.append((idx, "时间轴条目", "0s-3s（…）", line[:60]))
            if SHOT_TAG_PAT.search(line):
                issues.append((idx, "括号景别标签", "（远景·…）", line[:60]))
            # 台词括号七项检查见 scan_storyboard_shots（按镜块级，与 m2_gate 一致）
    # 台词长度（引号兼容 ""「」）
    for idx, raw in enumerate(text.splitlines(), start=1):
        for q in re.findall(r"[\"“\u300c](.+?)[\"”\u300d]", raw):
            if len(q) > 14 and re.search(r"（[男女]·", raw):
                issues.append((idx, "台词超长", "%d 字：%s" % (len(q), q[:20]), raw.strip()[:60]))
    if stage == "storyboard":
        issues.extend(scan_storyboard_shots(text, m1_text))
    # 平淡检测：与 m1_gate/m2_gate 的 13J 同源
    try:
        import flat_check
        if (u"待填" in text) or text.count(u"[") >= 3:   # 骨架稿不判平淡
            raise StopIteration
        _st = u"m2" if stage == u"storyboard" else u"m1"
        for _i, _k, _s in flat_check.scan_flat(text, _st):
            issues.append((_i, u"不平淡 " + _k, _s, u"全篇"))
    except StopIteration:
        pass
    except Exception:
        pass

    # 句法文体与分镜标签：与 m1_gate/m2_gate 的 13I、human_regress 同源
    try:
        import check_prose
        # 骨架稿（含 [待填] 类占位）不判文体，只判成品稿
        if (u"待填" in text) or (u"[" in text and u"待填" in text) or text.count(u"[") >= 3:
            raise StopIteration
        # 骨架占位行（[待填]、【拆解卡】、标题、说明）不算正文，先剔掉再查文体，避免骨架误报
        _lines = []
        for _ln in text.splitlines():
            _s = _ln.strip()
            if (not _s) or _s.startswith(u"#") or _s.startswith(u">") \
                    or (u"[" in _s and u"]" in _s) or _s.startswith(u"【"):
                continue
            _lines.append(_ln)
        _prose_text = u"\n".join(_lines)
        for _i, _k, _s in check_prose.scan_prose(_prose_text):
            issues.append((_i, u"句法文体 " + _k, _s, u"全篇"))
        for _i, _k, _s in check_prose.scan_board_labels(_prose_text):
            issues.append((_i, u"分镜标签 " + _k, _s, u"全篇"))
    except StopIteration:
        pass
    except Exception:
        pass
    # 新要求整合硬检：文本类与 M1、M2 门禁同源（结构类只由两道门禁查，避免短文本误伤）
    issues.extend(new_req_chk.as_issues(text, stage or "script"))
    # 爆款完全符合（B1/B2/B3/B5 文本级；B4/B6 是文件级，交剧本门）
    try:
        import boom_chk
        issues.extend(boom_chk.as_issues(text))
    except Exception:
        pass
    # 整篇级人话硬检（与 M1、M2 门禁同源，逐行规则查不到的靠这一层兜）
    for _c, _msg in human_chk.line_issues(text):
        issues.append((0, "人话硬检 " + _c, _msg, "全篇"))
    # 阶段一正文同样过「前后对不上」（C1/C3），避免只写进分镜才被拦
    if stage != "storyboard":
        for _c, _msg in consist_chk.line_issues(text, "m1"):
            issues.append((0, "前后对不上 " + _c, _msg, "全篇"))
    return issues


