def _section(text: str, start: str, end: str) -> str:
    i = text.find(start)
    if i < 0:
        return ""
    j = text.find(end, i + 1)
    return text[i:j] if j > i else text[i:]


def parse_storyboard_cards(text: str, script_text: str = "") -> dict:
    """从分镜稿里取五件套：场景（连带空间/光影/材质）/ 道具 / 角色（缺属性时回落到剧本台词标注）。"""
    scenes = []
    for m in re.finditer(r"###\s*场景\s*[A-Z]?\s*·\s*([^（(\n]+)（([^）]*)）(.+?)(?=\n###\s*场景|\n## )",
                         text, re.S):
        nm = m.group(1).strip()
        body = m.group(3)
        if not nm:
            continue
        info = {"name": nm, "inout": m.group(2).strip()}
        for k, key in (("空间锁定", "space"), ("光影基调", "light"), ("材质", "mat")):
            mm = re.search(r"-\s*%s[：:]\s*(.+)" % k, body)
            info[key] = mm.group(1).strip() if mm else ""
        scenes.append(info)
    prop_sec = _section(text, "道具卡", "\n## ")
    props = []
    for blk in re.split(r"^\s*\d+\.\s*\*\*", prop_sec, flags=re.M)[1:]:
        head, _, body = blk.partition("\n")
        nm = re.sub(r"[*⭐\s]", "", re.sub(r"（[^）]*）", "", head)).strip()
        key = ("题眼道具" in head) or ("⭐" in head)
        look = ""
        mm = re.search(r"-\s*外观[：:]\s*(.+)", body)
        if mm:
            look = mm.group(1).strip()
        if nm:
            props.append((nm, key, look))
    char_sec = _section(text, "角色卡", "\n## ")
    chars = re.findall(r"^\*\*(.+?)\*\*：(.+)$", char_sec, re.M)

    speakers = {}
    if script_text:
        for s in parse_script(script_text)["shots"]:
            for ln in s["lines"]:
                if ln["speaker"]:
                    speakers.setdefault(ln["speaker"], ln["tag"])
    if not chars and speakers:
        for nm, tag in speakers.items():
            parts = [x.strip() for x in tag.split("·")]
            chars.append((nm, "%s + %s + 族裔[ ] + 体型[ ] + 皮肤[ ] + 发型[ ] + 特征[ ]" % (
                parts[0] if parts else "[性别]", parts[1] if len(parts) > 1 else "[年龄]")))
    chars = [(nm, re.sub(r"\s*\+?\s*服装（[^）]*）\[ \]", "", attrs)) for nm, attrs in chars]
    return {"scenes": scenes, "props": props, "chars": chars}


