def scan_beat(text: str) -> list:
    """整段空转：一段里没有任何"手上有对象在做的事"，只有静姿或只有环境。
    与 scan_human（句子层）互补，扫的是段落层。"""
    hits = []
    paras = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
    numbered = [(int(re.match(r"^段\s*(\d+)", p).group(1)), p)
                for p in paras if re.match(r"^段\s*(\d+)", p)]
    if len(numbered) >= 3:
        paras = numbered
    else:
        paras = list(enumerate([p for p in paras if not p.startswith("#")], start=1))
    for i, p in paras:
        body = re.sub(r"^段\s*\d+\s*", "", p)
        if len(body) <= 12:
            hits.append((i, "空转段", "整段太短，没有可拍的动作", body[:40]))
            continue
        if any(v in body for v in BEAT_ACTION_VERBS):
            continue
        for pat, cat in BEAT_ENV_PATTERNS:
            if re.search(pat, body):
                hits.append((i, "空转段", cat, body[:40]))
                break
        else:
            hits.append((i, "空转段", "整段没有手上有对象在做的事", body[:40]))
    return hits


def scan_capability(text: str, manifest: list) -> list:
    """能力清单闸门：manifest 形如
    [{"from":1,"to":2,"forbid":[]},{"from":3,"to":5,"forbid":["煎","炒","撒盐","熬"]}]
    段落号落在区间内、正文出现 forbid 里的动作，即判越级。
    区间未覆盖的段号不判，避免误伤。"""
    issues = []
    paras = [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]
    for i, para in enumerate(paras, start=1):
        m = re.match(r"^\u6bb5\s*(\d+)", para)
        no = int(m.group(1)) if m else i
        for row in manifest:
            if not (row.get("from", 0) <= no <= row.get("to", 10 ** 6)):
                continue
            for w in row.get("forbid", []):
                if w in para:
                    issues.append((no, "能力越级", w, para[:50]))
    return issues


