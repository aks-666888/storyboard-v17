def build_prompts_offline(idea, genre, storyboard_text, script_text, cards) -> str:
    scenes = cards["scenes"] or ["[主场景]"]
    props = cards["props"] or [("[题眼道具]", True)]
    chars = cards["chars"] or [("[角色]", "[年龄] + [性别] + 族裔[ ] + 体型[ ] + 皮肤[ ] + 发型[ ]")]
    lines = ["## ⑦ 文生图提示词（角色 %d 个 / 场景 %d 个 / 道具 %d 个）\n" % (
        len(chars), len(scenes), len(props))]
    lines.append("> 生成方式：直接取自分镜稿五件套（场景结构/光影/材质、道具外观、角色属性均已填实）；"
                 "需要进一步润色时用 `stage3 --llm` 或按 `06_prompt.md` 交对话模型改。\n")

    lines.append("### ⑦a 角色三视图（锁脸基准，每角色一条）\n")
    for nm, attrs in chars:
        lines.append("%s｜三视图提示词：" % nm)
        tail = "" if ("服" in attrs or "鞋" in attrs) else \
            "；服装 [品类 + 颜色 + 旧度 + 污渍位置]；鞋 [款式 + 磨损]"
        lines.append("%s%s；全身自然站立，正面 / 四分之三侧面 / 背面 三个视角同图；"
                     "纯浅灰米白摄影棚背景，柔和均匀棚灯，无场景、无道具、无叙事元素。"
                     % (attrs, tail))
        lines.append(NEG_CHAR)
        lines.append("")

    lines.append("### ⑦b 场景图（每场景一条）\n")
    for sc in scenes:
        if isinstance(sc, dict):
            nm = sc["name"]
            body = "；".join(x.rstrip("。；") for x in [sc.get("inout") or "[室内/室外]", sc.get("space"),
                                                        sc.get("light"), sc.get("mat"), "无人物、无剧情、无文字"]
                             if x)
        else:
            nm = sc
            body = ("[室内/室外]；空间结构 [门在哪面墙 / 窗在哪 / 台在哪 / 大件在哪]；"
                    "主光来自 [方向] + 色温 [K]；材质 [墙皮/灰浆/木纹/金属 + 旧度]；"
                    "[地面墙面固定痕迹]")
        lines.append("%s｜场景图提示词：" % nm)
        lines.append(body + "。")
        lines.append(NEG_SCENE)
        lines.append("")

    lines.append("### ⑦c 关键道具图（每道具一条，题眼与反转标 ⭐）\n")
    for i, item in enumerate(props):
        nm, is_key, look = (item if len(item) == 3 else (item[0], item[1], ""))
        star = " ⭐" if is_key else ""
        lines.append("%s%s｜道具图提示词：" % (nm, star))
        lines.append((look.rstrip("。；") + "；单件平放或斜倚，纯中性背景，特写级细节。" if look else
                      "材质 [ ]；尺寸感 [ ]；磨损 [位置 + 程度]；反光面 [哑光/镜面/局部高光]；"
                      "裂纹/缺口 [位置]；附着物 [锈/胶/油/线头]；单件平放或斜倚，纯中性背景，特写级细节。"))
        lines.append(NEG_PROP)
        lines.append("")

    lines.append("## ⑧ 待拍板三问（每问带本次实际值）\n")
    lines.append("1. 形象：本次生成的是 %s 这 %d 个角色，按这份走还是换？" % (
        "、".join(c[0] for c in chars[:3]), len(chars)))
    lines.append("2. 场景 / 道具：本次是 %s 共 %d 个场景、%s 共 %d 个道具，保留还是加？" % (
        "、".join(s["name"] if isinstance(s, dict) else s for s in scenes[:3]), len(scenes),
        "、".join(p[0] for p in props[:3]), len(props)))
    lines.append("3. 改哪条？（给条号，我改完重跑自检）")
    lines.append("")
    lines.append("> 确认后本技能到此交付：画面生成、剪辑、发布不在技能范围。")
    return "\n".join(lines)
