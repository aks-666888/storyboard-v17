def classify(idea: str) -> dict:
    """按判据词给题材打分，返回主/次候选。"""
    text = idea or ""
    scores = []
    for g in GENRES:
        hit = [k for k in g["keys"] if k in text]
        scores.append((len(hit), g["id"], hit))
    scores.sort(key=lambda x: (-x[0], x[1]))
    best = scores[0]
    if best[0] == 0:
        return {
            "primary": GENRE_BY_ID["1.1"],
            "hits": [],
            "fallback": True,
            "note": "未命中任何判据词，按结构最近邻默认归入 1.1 情感线，交付中须明示。",
        }
    return {
        "primary": GENRE_BY_ID[best[1]],
        "hits": best[2],
        "fallback": False,
        "note": "命中判据词：" + "、".join(best[2]),
    }


# v2.9：时间服从画面——先有画面，再有秒数。单镜上限 15 秒，无下限。
# MIN_SHOT 只为算法兜底（防 0 秒），不是写作下限。
MIN_SHOT = 1
MAX_SHOT = 15
DEFAULT_SHOT_LEN = 8.0
PIC_CHARS_PER_SEC = 8.0      # 画面动作文字的语速：每秒 8 字
DIALOG_CHARS_PER_SEC = 4.5   # 台词语速：每秒 4.5 字
TOTAL_TOL = 0.10             # 内容合计与目标总时长的允许偏差


def suggest_scale(genre: dict, duration=None, shots=None, matched: dict = None, profile: dict = None) -> dict:
    """总时长由用户指定或六维现算；镜数不预设，交由剧本切段得出。

    这里只给区间与节奏，不再给出「每镜固定 N 秒」或「镜数 = 总时长÷N」。
    """
    p = (profile or {}).get(genre["id"], {})
    lo, hi = p.get("duration", genre["duration"][:2])
    if duration:
        raw = int(duration)
        source = "用户指定"
        head = "总时长由用户指定 %d 秒" % raw
    else:
        raw = int(round((lo + hi) / 2.0))
        source = "由同类爆款六维现算"
        lib_n0 = p.get("n_lib", p.get("n", 0))
        head = "§%s 库内 %d 条案例（本次取用 %d 条）；依据：%s；该类时长 %s → 取 %d 秒" % (
            genre["id"], lib_n0, len((matched or {}).get("items", [])),
            p.get("source") or "子类归纳",
            ("%d 秒" % lo) if lo == hi else ("%d–%d 秒" % (lo, hi)), raw)

    basis = "%s；镜数不预设（剧本切几段就是几镜）；每镜秒数由该镜画面与台词内容现算，不按字数反推" % head
    return {
        "total_seconds": raw, "shots": None,
        "shot_len": (MIN_SHOT, MAX_SHOT), "source": source,
        "max_shot": MAX_SHOT, "min_shot": MIN_SHOT,
        "rhythm": p.get("curve") or genre["rhythm"],
        "basis": basis,
        "range": (lo, hi), "profile_n": p.get("n", 0),
    }


def estimate_seconds_from_shot(shot: dict) -> float:
    """按该镜自身内容推时长：台词与画面动作取大者，加半秒起落。"""
    pic = str(shot.get("picture") or shot.get("desc") or "")
    dlg = str(shot.get("dialogue") or "")
    pic = re.sub(r"【[^】]*】", "", pic)   # 机位标注行不算画面字（v2.9.20 铁律14·四）
    pic_s = len(re.sub(r"\s+", "", pic)) / PIC_CHARS_PER_SEC
    dlg_s = len(re.sub(r"\s+", "", dlg)) / DIALOG_CHARS_PER_SEC
    core_s = max(pic_s, dlg_s)
    return max(float(MIN_SHOT), core_s + 0.5)


def content_seconds(shot) -> int:
    """对外口径：单镜按内容推出的整数秒（≥1，不在此处封顶 15）。"""
    return int(round(estimate_seconds_from_shot(shot))) if isinstance(shot, dict) else int(round(shot))


def scan_shots(text: str, total: int = 0) -> list:
    """阶段二专用：只抓超过 15 秒的镜；秒数合计只提示偏差，不判违规。"""
    issues = []
    hits = re.findall(r"镜\s*\d+\s*[（(]\s*(\d+(?:\.\d+)?)\s*秒[）)]", text)
    vals = [float(x) for x in hits]
    for i, v in enumerate(vals, 1):
        if v > MAX_SHOT:
            issues.append({"line": 0, "kind": "镜长越界",
                           "detail": "镜 %d 写 %s 秒，超过单镜上限 %d 秒，必须拆镜"
                                     % (i, hits[i - 1], MAX_SHOT)})
    if vals and total and abs(sum(vals) - total) > max(3.0, total * TOTAL_TOL):
        issues.append({"line": 0, "kind": "总时长偏差",
                       "detail": "各镜按内容合计 %s 秒，目标 %d 秒，偏差超 10%%；不要压秒，回改剧本加戏或删戏"
                                 % (int(sum(vals)), total)})
    return issues



# ---------------------------------------------------------------- 储备库解析

HEAD_SECTION = re.compile(r"^##\s*(\d\.\d)\s*(.*)$")
HEAD_ENTRY = re.compile(r"^###\s*\[(.*?)\]\s*(.*)$")
WORK_NAME = re.compile(r"《(.*?)》")


def parse_library(path: Path = None) -> list:
    path = path or LIBRARY
    if not path.exists():
        raise FileNotFoundError("爆款储备库不存在：%s" % path)
    entries, section, cur = [], None, None
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        m = HEAD_SECTION.match(line)
        if m:
            section = m.group(1)
            cur = None
            continue
        m = HEAD_ENTRY.match(line)
        if m:
            if section is None:  # 「记录结构」模板段，不算真实案例
                continue
            tag, rest = m.group(1), m.group(2)
            name_m = WORK_NAME.search(rest)
            title = name_m.group(1) if name_m else rest.strip(" ·")
            platform = rest[name_m.end():].strip(" ·") if name_m else ""
            cur = {"section": section, "tag": tag, "title": title,
                   "platform": platform, "lines": [], "raw": ""}
            entries.append(cur)
            continue
        if cur is not None and line:
            cur["lines"].append(line)
    for e in entries:
        e["raw"] = "\n".join(e["lines"])
        link = re.search(r"\[链接\]\((https?://[^)]+)\)", e["raw"])
        e["link"] = link.group(1) if link else ""
        dates = re.findall(r"检索于\s*(\d{4}-\d{2}-\d{2})", e["raw"])
        e["dates"] = dates
        e["latest"] = max(dates) if dates else ""
        e["borrow"] = _field(e["raw"], "可借鉴点")
        e["plot"] = _field(e["raw"], "剧情模式")
        e["style"] = _field(e["raw"], "风格基因")
    return entries


def _field(raw: str, name: str) -> str:
    m = re.search(r"-\s*%s：" % name, raw)
    if not m:
        return ""
    tail = raw[m.end():]
    nxt = re.search(r"\n-\s*(?:来源|播放|风格基因|剧情模式|可借鉴点|外观|戏用节点|作用)：", tail)
    return (tail[:nxt.start()] if nxt else tail).strip()


def library_stats(entries: list) -> dict:
    stats = {}
    for e in entries:
        s = e["section"] or "?"
        stats.setdefault(s, {"count": 0, "latest": ""})
        stats[s]["count"] += 1
        if e["latest"] and e["latest"] > stats[s]["latest"]:
            stats[s]["latest"] = e["latest"]
    return stats


def parse_single(path: Path = None) -> dict:
    """解析 P.1「单条案例实测表」：只取「核验方式」不是"待核"的行。

    行格式：| 子类 | 《作品》 | 平台 | 总时长(秒) | 镜数 | 平均镜长(秒) | 核验方式 | 核验日期 |
    """
    path = Path(path) if path else LIBRARY
    if not Path(path).exists():
        return {}
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    m = re.search(r"##\s*P\.1[^\n]*\n(.*?)(?=\n##\s|\Z)", text, re.S)
    if not m:
        return {}
    rows = {}
    for row in m.group(1).splitlines():
        cells = [c.strip() for c in row.strip().strip("|").split("|")]
        if len(cells) < 8 or not re.match(r"^\d\.\d$", cells[0]):
            continue
        title_m = re.search(r"《(.*?)》", cells[1])
        title = title_m.group(1) if title_m else cells[1]
        how = cells[6]
        if how.startswith("待核"):
            continue
        total = _pair(cells[3])
        shotn = re.findall(r"\d+", cells[4])
        avg = _pair(cells[5], default=(0, 0))
        if not shotn:
            shotn = ["0"]
        rows.setdefault(cells[0], []).append({
            "title": title, "platform": cells[2],
            "total": int(total[0]), "shots": int(shotn[0]),
            "avg": (avg[0] + avg[1]) / 2.0 if avg[1] else 0.0,
            "how": how, "date": cells[7],
        })
    return rows


def merge_profile(profile: dict, single: dict) -> dict:
    """覆盖规则：时长可用「平台页」口径；镜数/镜长只有「原片实测」才许覆盖，推定值一律不冒充实测。"""
    out = dict(profile or {})
    for sid, rows in (single or {}).items():
        if not rows:
            continue
        cur = dict(out.get(sid, {}))
        hard = [r for r in rows if r["how"].startswith("原片实测")]
        timed = [r for r in rows if r["how"].startswith(("原片实测", "平台页"))]
        totals = sorted(r["total"] for r in timed if r["total"])
        avgs = sorted(r["avg"] for r in hard if r["avg"])
        if totals:
            if "duration" in cur:
                cur["duration_lib"] = cur["duration"]
            cur["duration"] = (totals[0], totals[-1])
        if avgs:
            cur["shot_len"] = (avgs[0], avgs[-1])
        cur["n_lib"] = out.get(sid, {}).get("n", 0)
        cur["n"] = len(rows)
        cur["source"] = ("单条实测 %d 条（%s；镜长已核）" % (len(hard), "、".join(r["title"] for r in hard[:3])) if hard
                         else "单条口径 %d 条（%s；时长平台页，镜长按该类画像/推定）" % (
                             len(rows), "、".join(r["title"] for r in rows[:3])))
        out[sid] = cur
    return out


def parse_profile(path: Path = None, entries: list = None) -> dict:
    """解析储备库「子类六维画像」表：子类 → 时长/镜长/曲线/钩子/光影/台词密度/依据条数。"""
    path = Path(path) if path else LIBRARY
    if not Path(path).exists():
        return {}
    text = Path(path).read_text(encoding="utf-8", errors="replace")
    m = re.search(r"##\s*P\.0[^\n]*\n(.*?)(?=\n##\s|\Z)", text, re.S)
    table = m.group(1) if m else text
    out = {}
    for row in table.splitlines():
        cells = [c.strip() for c in row.strip().strip("|").split("|")]
        if len(cells) < 8 or not re.match(r"^\d\.\d$", cells[0]):
            continue
        lo, hi = _pair(cells[1])
        slo, shi = _pair(cells[2])
        out[cells[0]] = {
            "duration": (lo, hi), "shot_len": (slo, shi),
            "curve": cells[3], "hook": cells[4], "light": cells[5],
            "line": cells[6], "n": int(re.sub(r"\D", "", cells[7]) or 0),
        }
    return out


def _pair(s: str, default=(6, 9)) -> tuple:
    nums = re.findall(r"\d+(?:\.\d+)?", s)
    if len(nums) >= 2:
        return (float(nums[0]), float(nums[1]))
    if len(nums) == 1:
        return (float(nums[0]), float(nums[0]))
    return default


def match_works(genre: dict, entries: list, limit: int = 3, idea: str = "") -> dict:
    """子类内优先，按判据词/题材词重合度排序；不足则从最近邻子类补。"""
    def score(e):
        text = " ".join([e["tag"], e["title"], e["raw"]])
        s = 0
        for k in genre["keys"]:
            if k in text:
                s += 2
        if idea:
            for ch in set(idea):
                if ch in e["title"] or ch in e["tag"]:
                    s += 0.5
        return s

    own = [e for e in entries if e["section"] == genre["section"]]
    own.sort(key=score, reverse=True)
    picked = [dict(e, cross=False) for e in own[:limit]]

    if len(picked) < limit:
        for nb in genre.get("neighbor", []):
            extra = [e for e in entries if e["section"] == nb]
            extra.sort(key=score, reverse=True)
            for e in extra:
                if len(picked) >= limit:
                    break
                if e["title"] in [p["title"] for p in picked]:
                    continue
                picked.append(dict(e, cross=True, cross_from=nb))
    return {"items": picked, "enough": len(picked) >= limit,
            "own_count": len(own), "need": limit}


