def scan_human(text: str) -> list:
    """句子层读稿：抓物件当人使、抓没写手在哪的抽象动词与文学腔。
    只用于剧本／分镜正文，不扫规则文件。"""
    issues = []
    for idx, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith(("#", "-", "|", ">")):
            continue
        for pat, cat in HUMAN_BIND_PATTERNS:
            m = re.search(pat, line)
            if m:
                issues.append((idx, cat, m.group(0), line[:60]))
        for pat, cat in HUMAN_CAUSAL_PATTERNS:
            m = re.search(pat, line)
            if m:
                issues.append((idx, cat, m.group(0), line[:60]))
        for pat, cat in HUMAN_BODY_PATTERNS:
            m = re.search(pat, line)
            if m:
                issues.append((idx, cat, m.group(0), line[:60]))
        probe = re.sub(r"^\u6bb5\s*\d+\s*", "", line)
        for pat, cat in HUMAN_STORY_PATTERNS:
            m = re.search(pat, probe)
            if m:
                issues.append((idx, cat, m.group(0), line[:60]))
        for w, cat in HUMAN_VERBOSE:
            if w in line:
                issues.append((idx, cat, w, line[:60]))
    return issues


