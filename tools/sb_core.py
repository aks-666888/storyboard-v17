def scan_commonsense(text: str, trade: str = "", lex: dict = None) -> list:
    """行当常识词表：通用规则 + 本行当规则。命中即判违反常识。
    rule: {id, pat, why, unless}；unless 命中同段则不判（如当场被罚、捞出来重做）。"""
    if lex is None:
        lex = load_lexicon()
    issues = []
    rules = list(lex.get(u"\u901a\u7528", []))
    if trade:
        rules += list(lex.get(trade, []))
    for idx, raw in enumerate(text.splitlines(), start=1):
        line = raw.strip()
        if not line or line.startswith(("#", "-", "|", ">")):
            continue
        for r in rules:
            m = re.search(r.get("pat", ""), line)
            if not m:
                continue
            un = r.get("unless", "")
            if un and re.search(un, line):
                continue
            issues.append((idx, "行当常识", u"%s：%s" % (r.get("id", ""), r.get("why", "")), line[:50]))
    return issues


