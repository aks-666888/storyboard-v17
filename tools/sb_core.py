def rebuild_prompt(run_dir) -> bool:
    """按 run.json 留档参数，用当前工具版本重出 01_prompt.md。

    工具升版后旧单子会缺最新硬查，照它写稿必被交付门拦下；这里让盘上单子
    能一键跟着工具走，不靠人记着逐个手改。只动写稿单子，不碰任何稿子。
    """
    d = Path(run_dir)
    meta = d / "run.json"
    pf = d / "01_prompt.md"
    if not meta.exists() or not pf.exists():
        return False
    m = json.loads(meta.read_text(encoding="utf-8"))
    idea = (m.get("idea") or "").strip()
    if not idea:
        return False
    cls = classify(idea)
    genre = cls["primary"]
    if isinstance(m.get("matched"), list) and m["matched"]:
        # 优先用留档的本次取用片名，保证单子里的片名与稿子 ⓪ 登记一致，
        # 不因库内顺序变动而冒出没登记过的片名，把过程件检查误触发。
        matched = {"items": [
            {"title": x.get("title", ""), "platform": x.get("platform", ""),
             "borrow": x.get("borrow", ""), "cross": bool(x.get("cross")),
             "cross_from": x.get("cross_from", "")}
            for x in m["matched"]],
            "own_count": m.get("own_count", len(m["matched"])),
            "note": cls["note"]}
    else:
        matched = match_works(genre, parse_library(), limit=3, idea=idea)
        matched["note"] = cls["note"]
    opts = {"platform": m.get("platform"), "ratio": m.get("ratio"),
            "real": bool(m.get("real")), "ref": m.get("ref") or ""}
    scale = m.get("scale") or {}
    profile = merge_profile(parse_profile(), parse_single())
    new = build_stage1_prompt(idea, genre, matched, scale, opts, profile=profile)
    old = pf.read_text(encoding="utf-8")
    if new == old:
        return False
    write(pf, new)
    return True


