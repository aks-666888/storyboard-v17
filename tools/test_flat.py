# -*- coding: utf-8 -*-
"""平淡检测的跨题材考题：既考"该拦的拦得住"，也考"该放的不许乱杀"。"""
import io, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import flat_check as fc

FLAT = [
 # 纯布景
 u"院子里的灯亮着，桌上一只碗，墙根一堆柴。",
 u"屋子里很静，桌子靠着墙，窗户关着，地上有几片纸。",
 # 只有姿势，没有事
 u"老人坐在门口，看着村口那条路，天色慢慢暗下来。",
 u"她把包放在沙发上，坐下来，喘了口气。",
 # 短而无变化的一截
 u"他把碗放在桌上，站起身，看了看窗外。",
 # 连续四段没人说话、也没动作（M1 才用到第四段）
 u"墙根堆着柴，柴上落了一层灰，灰上又有几道手印。\n\n门框上挂着一串辣椒，辣椒红得发黑，绳子松了半截。\n\n桌上铺着一张旧报纸，报纸边角卷起来，压在一只空碗下。\n\n窗台上摆着半瓶酱油，瓶子歪着，瓶底一圈干掉的印。",
]

DRAMATIC = [
 # 动作链＋可见变化
 u"他把碗往桌上一放，碗里的汤晃出来，淌到账本上；他伸手去按，账本被按出一道湿印，师傅抬起头看他。",
 # 台词＋外部反应
 u"“钱不收。”他把钱推回去，客户的指头在钞票上压了压，脸一下沉下来，抓起钱往门口走，鞋跟磕在门槛上。",
 # 一件事接一件事，最后东西坏了
 u"她伸手去够灯绳，够不着，踮起脚，椅子在脚下一滑，人跟着歪过去，灯罩被撞掉，玻璃碎在地上。",
 # 纯台词交锋（不许因为没有动作被判平淡）
 u"“账我记了。”师傅把本子推过去，“人不记。”他低头看着那行字，手指在纸边上停住，“那我记什么。”",
 # 无人说话但每段都有动作（连写四段也不该判）
 u"他蹲下去，把散开的绳头重新绕回木桩，绕了三圈，最后一圈勒进泥里。\n\n他抬手把袖口往上撸，手臂上那道旧伤露出来，被汗浸得发红。\n\n他抓起地上的扳手，往车轮上一磕，磕出一声脆响，车轴跟着晃了一下。\n\n他把扳手扔回工具箱，箱盖砸下来，盖住了那排螺丝刀。",
]

M2_FLAT = u"" + u"## ③ 分镜脚本\n" + \
 u"**镜1（5秒）**\n屋里很静，桌子靠着墙，墙上挂着一只钟。\n" + \
 u"**镜2（5秒）**\n桌子上的碗摆得整齐，碗边一圈水印。\n" + \
 u"**镜3（5秒）**\n窗台上落着灰，灰上有一道指印，窗帘垂着一动不动。\n"

M2_OK = u"" + u"## ③ 分镜脚本\n" + \
 u"**镜1（5秒）**\n他抬手把门闩插上，门板被风顶得响了一声，缝隙里的光晃了晃。\n" + \
 u"**镜2（5秒）**\n他回手按住门板，掌心在木头上蹭出一道灰，门缝里的光停住不动。\n" + \
 u"**镜3（5秒）**\n他从兜里摸出钥匙，插进锁孔拧了半圈，锁舌弹出来搭在门框上。\n"

ok = True
for c in FLAT:
    h = fc.scan_flat(c, "m1")
    print(u"[%s] 平淡例 %d 处：%s" % (u"PASS" if h else u"FAIL", len(h), c[:26]))
    ok = ok and bool(h)
for c in DRAMATIC:
    h = fc.scan_flat(c, "m1")
    print(u"[%s] 有戏例 %d 处：%s" % (u"PASS" if not h else u"FAIL", len(h), c[:26]))
    for it in h:
        print(u"    -> [%s] %s" % (it[1], it[2]))
    ok = ok and not h
for name, text, stage, want in ((u"分镜三镜全是白描", M2_FLAT, u"m2", True),
                               (u"分镜三镜都有事", M2_OK, u"m2", False)):
    h = fc.scan_flat(text, stage)
    print(u"[%s] %s：%d 处" % (u"PASS" if bool(h) == want else u"FAIL", name, len(h)))
    ok = ok and bool(h) == want

cases = len(FLAT) + len(DRAMATIC) + 2
print(u"结论：%s（%d 例）" % (u"全部通过" if ok else u"有失败", cases))
sys.exit(0 if ok else 1)
